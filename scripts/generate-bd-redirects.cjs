// scripts/generate-bd-redirects.cjs
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { PATHS, writeIfChanged } = require('./lib/bd-util.cjs');
const routes = require('./lib/bd-routes.cjs');
const { RE_HOME } = require('./migrate-business-directories.cjs');
const { loadRegistry } = require('./lib/bd-registry.cjs');

// Emits 301s for directory pages whose country changed during the scope
// migration, into an idempotent marked block in _redirects.
//
// These URLs were generated locally but never deployed, so nothing is
// currently broken. The redirects are defensive: if a build of the previous
// shape ever reached production, or a link was shared from a preview, the old
// path still resolves instead of 404ing.

const START = '# bd-redirects:start — generated by scripts/generate-bd-redirects.cjs';
const END = '# bd-redirects:end';
const BLOCK_RE = /\n?# bd-redirects:start[\s\S]*?# bd-redirects:end\n?/g;

function buildRules() {
  const registry = loadRegistry();
  const bySlug = new Map();
  for (const entry of registry.directories) bySlug.set(entry.id, entry);

  const rules = [];
  for (const [legacyId, newCountry] of Object.entries(RE_HOME)) {
    // ids were re-issued during the same migration; find the record by its slug
    const newId = legacyId.replace(/^us-/, 'global-');
    const record = bySlug.get(newId) || bySlug.get(legacyId);
    if (!record) continue;
    const from = `/research/business-directories/united-states/${record.slug}/`;
    const to = routes.directoryPath(newCountry, record.slug);
    if (from === to) continue;
    rules.push({ from, to });
  }
  // Deterministic order so the file never churns.
  rules.sort((a, b) => (a.from < b.from ? -1 : a.from > b.from ? 1 : 0));
  return rules;
}

function render(rules) {
  if (!rules.length) return '';
  const width = Math.max(...rules.map((r) => r.from.length));
  const lines = rules.map((r) => `${r.from.padEnd(width)}  ${r.to}  301`);
  return `\n${START}\n# Business Directories scope migration: global platforms moved out of\n`
    + `# /united-states/ once country came to mean editorial scope, not headquarters.\n`
    + `${lines.join('\n')}\n${END}\n`;
}

function run(outRoot = PATHS.siteRoot) {
  const file = path.join(outRoot, '_redirects');
  const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  const cleaned = existing.replace(BLOCK_RE, '\n').replace(/\n{3,}/g, '\n\n').trimEnd();
  const rules = buildRules();
  const next = `${cleaned}\n${render(rules)}`.replace(/\n{3,}/g, '\n\n');
  const changed = writeIfChanged(file, next);
  return { rules, changed };
}

if (require.main === module) {
  const { rules, changed } = run();
  console.log(`${rules.length} redirect(s); _redirects ${changed ? 'updated' : 'unchanged'}.`);
}

module.exports = { run, buildRules, START, END };
